    private static final long[] POWERS_TEN = new long[NPOWERS];

    static {
        for (int i = 0; i < NPOWERS; i++) {
            POWERS_TEN[i] = Long.parseUnsignedLong(POWERS_TEN_FRAC[i]);
        }
    }

    /** typedef struct Fp { uint64_t frac; int exp; } Fp */
    private static final class Fp {
        long frac;
        int exp;

        Fp() {
        }

        Fp(long frac, int exp) {
            this.frac = frac;
            this.exp = exp;
        }
    }

    private FpconvDtoa() {
    }

    /** find_cachedpow10 - k 는 길이 1 배열로 돌려받음 */
    private static Fp findCachedpow10(int exp, int[] k) {
        final double oneLogTen = 0.30102999566398114;

        final int approx = (int) (-(exp + NPOWERS) * oneLogTen);
        int idx = (approx - FIRSTPOWER) / STEPPOWERS;

        while (true) {
            int current = exp + POWERS_TEN_EXP[idx] + 64;

            if (current < EXPMIN) {
                idx++;
                continue;
            }

            if (current > EXPMAX) {
                idx--;
                continue;
            }

            k[0] = FIRSTPOWER + idx * STEPPOWERS;

            return new Fp(POWERS_TEN[idx], POWERS_TEN_EXP[idx]);
        }
    }

    // --- fpconv_dtoa.c ---

    private static Fp buildFp(double d) {
        long bits = Double.doubleToRawLongBits(d);

        Fp fp = new Fp();
        fp.frac = bits & FRACMASK;
        fp.exp = (int) ((bits & EXPMASK) >>> 52);

        if (fp.exp != 0) {
            fp.frac += HIDDENBIT;
            fp.exp -= EXPBIAS;

        } else {
            fp.exp = -EXPBIAS + 1;
        }

        return fp;
    }

    private static void normalize(Fp fp) {
        while ((fp.frac & HIDDENBIT) == 0) {
            fp.frac <<= 1;
            fp.exp--;
        }

        int shift = 64 - 52 - 1;
        fp.frac <<= shift;
        fp.exp -= shift;
    }

    private static void getNormalizedBoundaries(Fp fp, Fp lower, Fp upper) {
        upper.frac = (fp.frac << 1) + 1;
        upper.exp = fp.exp - 1;

        while ((upper.frac & (HIDDENBIT << 1)) == 0) {
            upper.frac <<= 1;
            upper.exp--;
        }

        int uShift = 64 - 52 - 2;

        upper.frac <<= uShift;
        upper.exp = upper.exp - uShift;

        int lShift = fp.frac == HIDDENBIT ? 2 : 1;

        lower.frac = (fp.frac << lShift) - 1;
        lower.exp = fp.exp - lShift;

        lower.frac <<= lower.exp - upper.exp;
        lower.exp = upper.exp;
    }

    private static Fp multiply(Fp a, Fp b) {
        final long lomask = 0x00000000FFFFFFFFL;

        long ahBl = (a.frac >>> 32) * (b.frac & lomask);
        long alBh = (a.frac & lomask) * (b.frac >>> 32);
        long alBl = (a.frac & lomask) * (b.frac & lomask);
        long ahBh = (a.frac >>> 32) * (b.frac >>> 32);

        long tmp = (ahBl & lomask) + (alBh & lomask) + (alBl >>> 32);
        /* round up */
        tmp += 1L << 31;

        return new Fp(ahBh + (ahBl >>> 32) + (alBh >>> 32) + (tmp >>> 32), a.exp + b.exp + 64);
    }

    private static void roundDigit(byte[] digits, int ndigits, long delta, long rem, long kappa, long frac) {
        while (ult(rem, frac) && !ult(delta - rem, kappa)
                && (ult(rem + kappa, frac) || ult(rem + kappa - frac, frac - rem))) {
            digits[ndigits - 1]--;
            rem += kappa;
        }
    }

    private static int generateDigits(Fp fp, Fp upper, Fp lower, byte[] digits, int[] bigK) {
        long wfrac = upper.frac - fp.frac;
        long delta = upper.frac - lower.frac;

        Fp one = new Fp();
        one.frac = 1L << -upper.exp;
        one.exp = upper.exp;

        long part1 = upper.frac >>> -one.exp;
        long part2 = upper.frac & (one.frac - 1);

        int idx = 0;
        int kappa = 10;
        int divp;
        /* 1000000000 */
        for (divp = 10; kappa > 0; divp++) {
            long div = TENS[divp];
            long digit = Long.divideUnsigned(part1, div);

            if (digit != 0 || idx != 0) {
                digits[idx++] = (byte) (digit + '0');
            }

            part1 -= digit * div;
            kappa--;

            long tmp = (part1 << -one.exp) + part2;
            if (!ult(delta, tmp)) {
                bigK[0] += kappa;
                roundDigit(digits, idx, delta, tmp, div << -one.exp, wfrac);

                return idx;
            }
        }

        /* 10 */
        int unit = 18;

        while (true) {
            part2 *= 10;
            delta *= 10;
            kappa--;

            // unsigned digit - 32비트로 잘림
            long digit = (part2 >>> -one.exp) & 0xFFFFFFFFL;
            if (digit != 0 || idx != 0) {
                digits[idx++] = (byte) (digit + '0');
            }

            part2 &= one.frac - 1;
            if (ult(part2, delta)) {
                bigK[0] += kappa;
                roundDigit(digits, idx, delta, part2, one.frac, wfrac * TENS[unit]);

                return idx;
            }

            unit--;
        }
    }

    private static int grisu2(double d, byte[] digits, int[] bigK) {
        Fp w = buildFp(d);

        Fp lower = new Fp();
        Fp upper = new Fp();
        getNormalizedBoundaries(w, lower, upper);

        normalize(w);

        int[] k = new int[1];
        Fp cp = findCachedpow10(upper.exp, k);

        w = multiply(w, cp);
        upper = multiply(upper, cp);
        lower = multiply(lower, cp);

        lower.frac++;
        upper.frac--;

        bigK[0] = -k[0];

        return generateDigits(w, upper, lower, digits, bigK);
    }

    private static int emitDigits(byte[] digits, int ndigits, byte[] dest, int at, int bigK, boolean neg) {
        int exp = Math.abs(bigK + ndigits - 1);

        /* write plain integer */
        if (bigK >= 0 && (exp < (ndigits + 7))) {
            System.arraycopy(digits, 0, dest, at, ndigits);
            Arrays.fill(dest, at + ndigits, at + ndigits + bigK, (byte) '0');

            return ndigits + bigK;
        }

        /* write decimal w/o scientific notation */
        if (bigK < 0 && (bigK > -7 || exp < 4)) {
            int offset = ndigits - Math.abs(bigK);
            /* fp < 1.0 -> write leading zero */
            if (offset <= 0) {
                offset = -offset;
                dest[at] = '0';
                dest[at + 1] = '.';
                Arrays.fill(dest, at + 2, at + 2 + offset, (byte) '0');
                System.arraycopy(digits, 0, dest, at + offset + 2, ndigits);

                return ndigits + 2 + offset;

                /* fp > 1.0 */
            } else {
                System.arraycopy(digits, 0, dest, at, offset);
                dest[at + offset] = '.';
                System.arraycopy(digits, offset, dest, at + offset + 1, ndigits - offset);

                return ndigits + 1;
            }
        }

        /* write decimal w/ scientific notation */
        ndigits = Math.min(ndigits, 18 - (neg ? 1 : 0));

        int idx = at;
        dest[idx++] = digits[0];

        if (ndigits > 1) {
            dest[idx++] = '.';
            System.arraycopy(digits, 1, dest, idx, ndigits - 1);
            idx += ndigits - 1;
        }

        dest[idx++] = 'e';

        byte sign = (byte) (bigK + ndigits - 1 < 0 ? '-' : '+');
        dest[idx++] = sign;

        int cent = 0;

        if (exp > 99) {
            cent = exp / 100;
            dest[idx++] = (byte) (cent + '0');
            exp -= cent * 100;
        }
        if (exp > 9) {
            int dec = exp / 10;
            dest[idx++] = (byte) (dec + '0');
            exp -= dec * 10;

        } else if (cent != 0) {
            dest[idx++] = '0';
        }

        dest[idx++] = (byte) (exp % 10 + '0');

        return idx - at;
    }

    private static int filterSpecial(double fp, byte[] dest, int at) {
        if (fp == 0.0) {
            dest[at] = '0';
            return 1;
        }

        long bits = Double.doubleToRawLongBits(fp);

        boolean nan = (bits & EXPMASK) == EXPMASK;

        if (!nan) {
            return 0;
        }

        if ((bits & FRACMASK) != 0) {
            dest[at] = 'n';
            dest[at + 1] = 'a';
            dest[at + 2] = 'n';

        } else {
            dest[at] = 'i';
            dest[at + 1] = 'n';
            dest[at + 2] = 'f';
        }

        return 3;
    }

    /** int fpconv_dtoa(double d, char dest[24]) - 반환값은 쓴 바이트 수 */
    static int fpconvDtoa(double d, byte[] dest) {
        byte[] digits = new byte[18];

        int strLen = 0;
        boolean neg = false;

        if ((Double.doubleToRawLongBits(d) & SIGNMASK) != 0) {
            dest[0] = '-';
            strLen++;
            neg = true;
        }

        int spec = filterSpecial(d, dest, strLen);

        if (spec != 0) {
            return strLen + spec;
        }

        int[] bigK = {0};
        int ndigits = grisu2(d, digits, bigK);

        strLen += emitDigits(digits, ndigits, dest, strLen, bigK[0], neg);

        return strLen;
    }

    /** uint64_t a < b */
    private static boolean ult(long a, long b) {
        return Long.compareUnsigned(a, b) < 0;
    }
